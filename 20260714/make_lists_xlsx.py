COUNT_UNITS = {"個", "本", "束", "袋", "株", "枚", "玉", "缶", "箱", "切", "尾", "房", "パック"}

def fmt_qty(qty, unit):
    """容量を現実的な値に丸める"""
    if unit in COUNT_UNITS:
        return max(1, round(qty))
    q = qty if qty < 100 else round(qty / 10) * 10
    return round(q)

def nice_price(p):
    """スーパーらしい「8円」で終わる価格に丸める"""
    return max(18, int(round(p / 10)) * 10 - 2)

def gen_variants(cat, unit, q, up, dom, imp, tags):
    """1カテゴリから容量・パック・特売・こだわり・輸入・健康属性のバリエーションを展開"""
    rows = []
    def push(prefix, qty, packs, factor, origin, tag=""):
        size = fmt_qty(qty, unit)
        price = nice_price(up * size * packs * factor)
        name = f"{prefix}{cat} {size}{unit}" + (f"×{packs}" if packs > 1 else "")
        rows.append([cat, name, price, size, unit, packs, origin, tag])

    # 容量ラダー（小/標準/徳用）
    if unit in COUNT_UNITS and q <= 2:
        ladder = [(q, 1.0, ""), (q * 3, 0.90, ""), (q * 6, 0.85, "徳用 ")]
    else:
        bulk = 2.0 if unit == "ml" else 2.5
        ladder = [(q * 0.5, 1.15, ""), (q, 1.0, ""), (q * bulk, 0.85, "徳用 ")]
    for qty, factor, prefix in ladder:
        push(prefix, qty, 1, factor, dom)

    push("", q, 2, 0.92, dom)          # 2個パック（まとめ買い割引）
    push("", q, 3, 0.88, dom)          # 3個パック（まとめ買い割引）
    push("特売 ", q, 1, 0.78, dom)      # 特売品
    push("こだわり", q, 1, 1.60, dom)   # プレミアム品

    if imp:  # 輸入品（割安）
        push("", q, 1, 0.70, imp)
        push("大容量 ", q * 3, 1, 0.55, imp)
        push("特売 ", q, 1, 0.62, imp)

    big = q * 3 if (unit in COUNT_UNITS and q <= 2) else q * 2
    for tag in tags[:2]:  # 健康属性品（割高）: 標準サイズと大きめの2種
        push(f"{tag} ", q, 1, 1.45, dom, tag)
        push(f"{tag} ", big, 1, 1.30, dom, tag)

    return rows

SUPER = []
for spec in BASE:
    SUPER.extend(gen_variants(*spec))

# ======================================================================
# Excel出力
# ======================================================================
def make_sheet(wb, title, headers, rows, widths, date_col=None):
    ws = wb.active
    ws.title = title
    ws.append(headers)
    for c in ws[1]:
        c.font = HEADER_FONT
        c.fill = HEADER_FILL
        c.alignment = Alignment(horizontal="center")
    for row in rows:
        ws.append(row)
    for r in ws.iter_rows(min_row=2):
        for c in r:
            c.font = BODY_FONT
            if date_col and c.column_letter == date_col:
                c.number_format = "yyyy/mm/dd"
    for i, w in enumerate(widths):
        ws.column_dimensions[chr(ord("A") + i)].width = w
    ws.freeze_panes = "A2"
    ws.auto_filter.ref = ws.dimensions

